import Foundation

/// Finding and removing seeded weigh-ins that were saved by mistake.
///
/// Early versions filled an empty store with six weeks of invented mornings
/// so the chart meant something on first launch, then saved the whole array
/// the first time a real weigh-in was recorded — writing the invented ones
/// into the user's file beside the real one. New installs cannot hit that any
/// more (`WeightStore.isShowingSampleEntries`), but a file that already has
/// them needs a way out, and nothing in the stored row says which is which.
///
/// Except the clock. The seeded entries are generated by subtracting whole
/// days from the instant the app launched, so every one of them carries the
/// **same time of day down to the second**. A real weigh-in cannot do that:
/// stepping on a scale at 08:09:52 twenty-one mornings running is not a thing
/// a person or a scale does. That signature, plus the fact that the generator
/// never produced body composition, is enough to identify them exactly.
///
/// The bar is set at eight so that a coincidence cannot reach it. Two
/// weigh-ins sharing a second is luck; eight is a loop.
enum SampleWeighIn {

    /// How many entries must share one exact second before the cluster is
    /// read as generated rather than weighed.
    static let clusterThreshold = 8

    /// The entries that look seeded.
    static func seeded(in entries: [WeightEntry], calendar: Calendar) -> [WeightEntry] {
        var byTimeOfDay: [Int: [WeightEntry]] = [:]
        for entry in entries where !entry.hasComposition {
            byTimeOfDay[secondOfDay(entry.date, calendar: calendar), default: []].append(entry)
        }
        return byTimeOfDay.values
            .filter { $0.count >= clusterThreshold }
            .flatMap { $0 }
    }

    /// Everything that is not seeded, in date order.
    static func purge(_ entries: [WeightEntry], calendar: Calendar) -> [WeightEntry] {
        let doomed = Set(seeded(in: entries, calendar: calendar).map(\.id))
        guard !doomed.isEmpty else { return entries }
        return entries.filter { !doomed.contains($0.id) }.sorted { $0.date < $1.date }
    }

    private static func secondOfDay(_ date: Date, calendar: Calendar) -> Int {
        let parts = calendar.dateComponents([.hour, .minute, .second], from: date)
        return (parts.hour ?? 0) * 3_600 + (parts.minute ?? 0) * 60 + (parts.second ?? 0)
    }
}
